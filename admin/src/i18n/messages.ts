export function interpolate(
  template: string,
  vars: Record<string, string | number>,
): string {
  let s = template
  for (const [k, v] of Object.entries(vars)) {
    const re = new RegExp(`\\{${k}\\}`, 'g')
    s = s.replace(re, String(v))
  }
  return s
}
